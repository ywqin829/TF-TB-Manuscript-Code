wb <- createWorkbook()
header_style <- createStyle(
  fontColour = "#FFFFFF",
  fgFill = "#1F4E79",
  halign = "center",
  textDecoration = "bold",
  border = "Bottom"
)

for (sheet_name in names(tables)) {
  addWorksheet(wb, sheet_name)
  writeData(wb, sheet_name, tables[[sheet_name]], withFilter = TRUE)
  freezePane(wb, sheet_name, firstRow = TRUE)
  addStyle(
    wb,
    sheet_name,
    header_style,
    rows = 1,
    cols = seq_len(max(1, ncol(tables[[sheet_name]]))),
    gridExpand = TRUE
  )
  setColWidths(
    wb,
    sheet_name,
    cols = seq_len(max(1, ncol(tables[[sheet_name]]))),
    widths = "auto"
  )
}

saveWorkbook(
  wb,
  out_path("supplement", "Supplementary_Tables.xlsx"),
  overwrite = TRUE
)

